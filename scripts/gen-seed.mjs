// Generates db/seed.sql from the app's data modules so the database and the
// client never disagree about books, quest order, artifacts or bosses.
// Usage: node scripts/gen-seed.mjs > db/seed.sql
import { BOOKS, QUEST_ORDER } from '../quest/js/data/books.js';
import { ARTIFACTS, BOSSES } from '../quest/js/data/lore.js';

const q = v => `'${String(v).replace(/'/g, "''")}'`;
const out = ['-- GENERATED by scripts/gen-seed.mjs — do not edit by hand.', 'begin;'];
out.push('insert into books (num, name, chapters, testament, section, quest_order) values');
out.push(BOOKS.map(b => `  (${b.num}, ${q(b.name)}, ${b.chapters}, ${q(b.testament)}, ${q(b.section)}, ${QUEST_ORDER.indexOf(b.num) + 1})`).join(',\n') + ';');
out.push('insert into bosses (section, name, icon) values');
out.push(Object.entries(BOSSES).map(([s, b]) => `  (${q(s)}, ${q(b.name)}, ${q(b.icon)})`).join(',\n') + ';');
out.push('insert into artifacts (book_num, icon, name, lore) values');
out.push(Object.entries(ARTIFACTS).map(([n, a]) => `  (${n}, ${q(a.icon)}, ${q(a.name)}, ${q(a.lore)})`).join(',\n') + ';');
out.push('commit;');
console.log(out.join('\n'));
